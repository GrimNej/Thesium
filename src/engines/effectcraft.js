// effectcraft: a clean-room After Effects in Rust (github.com/storytold/effectcraft).
// The film is an After Effects-style script, film/build.jsx, that builds the whole project
// from nothing. Thesium runs it headless, then renders frames and sequences with the CLI.
import { createHash } from 'node:crypto';
import { existsSync } from 'node:fs';
import { mkdir, readFile, readdir, rm, stat, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { run } from '../core/proc.js';
import { FONT_DIR, inside } from '../core/paths.js';
import { filmInfo } from '../core/manifest.js';
import { scan } from './rules.js';

const WRAPPER = '.thesium-build.jsx';

/** Where effectcraft-cli might be installed, most specific first. */
async function candidates() {
  const list = [];
  if (process.env.THESIUM_EFFECTCRAFT) list.push(process.env.THESIUM_EFFECTCRAFT);
  const exe = process.platform === 'win32' ? 'effectcraft-cli.exe' : 'effectcraft-cli';
  for (const dir of (process.env.PATH || '').split(path.delimiter)) if (dir) list.push(path.join(dir, exe));
  if (process.platform === 'win32') {
    const local = path.join(process.env.LOCALAPPDATA || '', 'Programs', 'EffectCraft');
    // Portable installs: Programs\EffectCraft\<version>\<folder>\effectcraft-cli.exe, newest first.
    const versions = (await readdir(local).catch(() => [])).sort(compareVersions).reverse();
    for (const v of versions) {
      list.push(path.join(local, v, exe));
      for (const sub of await readdir(path.join(local, v)).catch(() => [])) list.push(path.join(local, v, sub, exe));
    }
    list.push(path.join(local, exe), path.join(process.env.ProgramFiles || 'C:\\Program Files', 'EffectCraft', exe));
  } else {
    list.push('/usr/bin/effectcraft-cli', '/usr/local/bin/effectcraft-cli', path.join(os.homedir(), '.local', 'bin', 'effectcraft-cli'));
    list.push('/Applications/EffectCraft.app/Contents/MacOS/effectcraft-cli');
  }
  return list;
}

/** @param {string} a @param {string} b */
function compareVersions(a, b) {
  const pa = a.split(/[.-]/).map(Number);
  const pb = b.split(/[.-]/).map(Number);
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    const d = (pa[i] || 0) - (pb[i] || 0);
    if (d) return d;
  }
  return 0;
}

/** @returns {Promise<string | undefined>} */
export async function findEffectCraft() {
  for (const file of await candidates()) if (file && existsSync(file)) return file;
  return undefined;
}

/** Fonts EffectCraft can resolve: fixed-weight instances, then the film's own. @param {string} workspace */
function fontEnv(workspace) {
  const dirs = [path.join(FONT_DIR, 'static'), path.join(workspace, 'assets', 'fonts')];
  const extra = process.env.EFFECTCRAFT_FONT_DIRS ? [process.env.EFFECTCRAFT_FONT_DIRS] : [];
  return { EFFECTCRAFT_FONT_DIRS: [...dirs, ...extra].join(path.delimiter) };
}

const posix = (p) => p.replaceAll('\\', '/');

/** Files whose content decides the built project. @param {string} dir */
async function hashTree(dir, hash) {
  for (const entry of (await readdir(dir, { withFileTypes: true }).catch(() => [])).sort((a, b) => a.name.localeCompare(b.name))) {
    if (entry.name.startsWith('.')) continue;
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) await hashTree(file, hash);
    else if (/\.(jsx|js|json|txt|csv)$/i.test(entry.name)) hash.update(entry.name).update(await readFile(file));
  }
}

/**
 * The script EffectCraft runs: the film's facts as THESIUM, the kit, the film, then a report
 * of what was built so Thesium can check comp settings and fonts.
 * @param {string} workspace
 * @param {object} info
 * @param {string} entry
 * @param {string} comp
 */
function wrapper(workspace, info, entry, comp) {
  return `// Generated by Thesium for every build. Do not edit: change ${entry} instead.
var THESIUM = ${JSON.stringify({ ...info, root: posix(path.resolve(workspace)), comp })};
#include "kit/effectcraft/thesium.jsx"
#include "${posix(entry)}"
(function () {
  var report = { comps: [], texts: [], missingFonts: [] };
  var families = {};
  for (var i = 1; i <= app.project.numItems; i++) {
    var item = app.project.item(i);
    if (!(item instanceof CompItem)) continue;
    report.comps.push({ name: item.name, width: item.width, height: item.height, fps: item.frameRate, duration: item.duration, layers: item.numLayers });
    for (var j = 1; j <= item.numLayers; j++) {
      var layer = item.layer(j);
      if (!(layer instanceof TextLayer)) continue;
      var doc = layer.property("Source Text").value;
      var key = doc.font + "|" + (doc.fontStyle || "Regular");
      report.texts.push({ comp: item.name, layer: layer.name, font: doc.font, style: doc.fontStyle });
      if (families[key] === undefined) {
        var found = app.run("text.fonts", { query: doc.font }).families || [];
        var ok = false;
        for (var k = 0; k < found.length; k++)
          if (found[k].family === doc.font && (!doc.fontStyle || found[k].styles.indexOf(doc.fontStyle) >= 0)) ok = true;
        families[key] = ok;
        if (!ok) report.missingFonts.push({ comp: item.name, layer: layer.name, font: doc.font, style: doc.fontStyle });
      }
    }
  }
  writeLn("THESIUM_REPORT " + JSON.stringify(report));
})();
`;
}

const STARTER = (m) => `// ${m.title}: built by EffectCraft from this script on every render.
// THESIUM holds the film's size, fps, duration and params; T is the Thesium kit
// (kit/effectcraft/thesium.jsx). Everything is keyframes, expressions and effects:
// deterministic for any frame, in any order. See the EffectCraft engine guide.

var comp = T.film(); // the composition Thesium renders, sized from thesium.json

// Build the film here: layers, keyframes, effects, cameras, lights.
`;

const RULES = [
  { pattern: /Math\.random\s*\(/, level: 'error', message: 'Math.random() makes each build different; use T.rand(seed)' },
  { pattern: /\b(Date\.now|new Date\s*\()/, level: 'error', message: 'Builds must not depend on the clock' },
  { pattern: /\bSocket\s*\(|system\.callSystem|\.execute\s*\(/, level: 'error', message: 'Builds must not use the network or run programs' },
  { pattern: /setTimeout|app\.scheduleTask/, level: 'error', message: 'Scheduled tasks do not run in headless builds' },
  { pattern: /"[A-Za-z]:[\\/]|'[A-Za-z]:[\\/]/, level: 'warning', message: 'Absolute paths break when the film folder moves; use T.asset("assets/…")' },
  { pattern: /\.font\s*=\s*["'][^"']+-[A-Z][a-z]/, level: 'warning', message: 'PostScript font names fall back silently in EffectCraft; use T.text({ font: "Family", style: "Bold" })' },
];

/** @type {import('./index.js').Engine & { cli: () => Promise<string> }} */
export const effectcraftEngine = {
  id: 'effectcraft',
  label: 'EffectCraft (After Effects-style compositor)',
  summary: 'Layers, keyframes, 300+ effects (glow, fractal textures, flares), text animators, 3D cameras and lights',
  guide: 'engines/effectcraft.md',

  async cli() {
    const cli = await findEffectCraft();
    if (!cli)
      throw new Error(
        'effectcraft-cli was not found. Install EffectCraft (https://github.com/storytold/effectcraft/releases) or set THESIUM_EFFECTCRAFT to effectcraft-cli.',
      );
    return cli;
  },

  async detect() {
    const cli = await findEffectCraft();
    if (!cli)
      return {
        ok: false,
        detail: 'effectcraft-cli not found',
        fix: 'Download EffectCraft from https://github.com/storytold/effectcraft/releases (Windows: the portable zip into %LOCALAPPDATA%\\Programs\\EffectCraft\\<version>), or set THESIUM_EFFECTCRAFT',
      };
    try {
      const { stdout } = await run(cli, ['--version'], { timeout: 20000 });
      return { ok: true, version: stdout.trim().split(/\s+/).pop(), detail: cli };
    } catch (error) {
      return { ok: false, detail: `${cli} did not start: ${/** @type {Error} */ (error).message}` };
    }
  },

  async scaffold(workspace, m) {
    const file = inside(workspace, m.entry);
    await mkdir(path.dirname(file), { recursive: true });
    if (await stat(file).catch(() => undefined)) return [];
    await writeFile(file, STARTER(m));
    return [m.entry];
  },

  async lint(workspace, m) {
    const entry = inside(workspace, m.entry);
    if (!(await stat(entry).catch(() => undefined))) return [{ level: 'error', message: `Entry not found: ${m.entry}` }];
    /** @type {import('./index.js').Finding[]} */
    const findings = [];
    const dir = path.dirname(entry);
    for (const name of await readdir(dir)) {
      if (!/\.jsx?$/i.test(name)) continue;
      findings.push(...scan(await readFile(path.join(dir, name), 'utf8'), posix(path.relative(workspace, path.join(dir, name))), /** @type {any} */ (RULES)));
    }
    if (m.motionBlur.samples > 1)
      findings.push({ level: 'warning', message: 'motionBlur.samples > 1 multiplies render time; EffectCraft has native motion blur (T.motionBlur(comp) and layer.motionBlur = true)' });
    return findings;
  },

  async build(workspace, m, o) {
    const project = await buildProject(workspace, m, o);
    return `built ${path.relative(workspace, project.file)} (${project.report.comps.map((c) => `${c.name} ${c.width}×${c.height}`).join(', ')})${project.cached ? ' [unchanged]' : ''}`;
  },

  async open(workspace, m, o) {
    const cli = await effectcraftEngine.cli();
    const { file } = await buildProject(workspace, m, o);
    const comp = m.engineOptions?.effectcraft?.comp || 'Film';
    const env = fontEnv(workspace);
    const scale = o.scale && o.scale > 0 && o.scale < 1 ? o.scale : 1;
    const tmp = path.join(workspace, '.thesium', 'frames');
    await mkdir(tmp, { recursive: true });
    let n = 0;
    /** Renders exact times in one process. @param {number[]} times @param {string[]} files */
    const batch = async (times, files) => {
      const args = [file, 'comp.open', JSON.stringify({ comp })];
      times.forEach((t, i) =>
        args.push('comp.saveFrameAs', JSON.stringify({ path: posix(path.resolve(files[i])), time: clamp(t, m), ...(scale < 1 ? { scale } : {}) })),
      );
      await run(cli, ['run', ...args, '--json'], { env, timeout: 600000, signal: o.signal });
    };
    return {
      format: 'png',
      parallel: 1,
      async frame(t) {
        const out = path.join(tmp, `f-${process.pid}-${n++}.png`);
        await batch([t], [out]);
        const data = await readFile(out);
        await rm(out, { force: true });
        return data;
      },
      async frames(times, files) {
        const pngs = files.map((f, i) => (f.toLowerCase().endsWith('.png') ? f : path.join(tmp, `b-${process.pid}-${n++}-${i}.png`)));
        for (let i = 0; i < times.length; i += 40) await batch(times.slice(i, i + 40), pngs.slice(i, i + 40));
        return pngs;
      },
      async sequence({ from, to, fps, dir, onProgress }) {
        await rm(dir, { recursive: true, force: true });
        await mkdir(dir, { recursive: true });
        const resolution = scale < 1 ? String(scale) : 'full';
        const total = Math.round((to - from) * fps);
        // Progress by counting written frames: works on every EffectCraft release.
        const timer = setInterval(async () => {
          const count = (await readdir(dir).catch(() => [])).length;
          if (count) onProgress?.(Math.min(count, total), total);
        }, 2000);
        try {
          await run(
            cli,
            ['render', file, '--comp', comp, '--out', posix(path.join(dir, 'f_[######].png')), '--format', 'png', '--start', String(from), '--end', String(to), '--fps', String(fps), '--resolution', resolution],
            { env, timeout: 6 * 3600000, signal: o.signal },
          );
        } finally {
          clearInterval(timer);
        }
        onProgress?.(total, total);
        return { pattern: path.join(dir, 'f_%06d.png'), format: 'png' };
      },
      async close() {},
    };
  },
};

/** @param {number} t @param {import('../core/manifest.js').Manifest} m */
const clamp = (t, m) => Math.max(0, Math.min(m.duration - 1 / m.fps / 2, t));

/**
 * Runs film/build.jsx (with the kit and parameter values) into .thesium/build/<hash>.ecproj.
 * Rebuilds only when the source, kit, parameters or manifest changed.
 * @param {string} workspace
 * @param {import('../core/manifest.js').Manifest} m
 * @param {import('./index.js').OpenOptions} o
 */
export async function buildProject(workspace, m, o) {
  const cli = await effectcraftEngine.cli();
  const entry = inside(workspace, m.entry);
  if (!(await stat(entry).catch(() => undefined))) throw new Error(`Entry not found: ${m.entry}`);
  const comp = m.engineOptions?.effectcraft?.comp || 'Film';
  const info = filmInfo(m, o.params);
  const hash = createHash('sha256').update(JSON.stringify({ info, comp, entry: m.entry }));
  await hashTree(path.join(workspace, 'film'), hash);
  await hashTree(path.join(workspace, 'kit', 'effectcraft'), hash);
  const key = hash.digest('hex').slice(0, 16);
  const dir = path.join(workspace, '.thesium', 'build');
  const file = path.join(dir, `film-${key}.ecproj`);
  const reportFile = `${file}.json`;
  if (existsSync(file) && existsSync(reportFile))
    return { file, report: JSON.parse(await readFile(reportFile, 'utf8')), cached: true };
  await mkdir(dir, { recursive: true });
  const script = path.join(workspace, WRAPPER);
  await writeFile(script, wrapper(workspace, info, posix(path.relative(workspace, entry)), comp));
  const lines = [];
  let result;
  try {
    result = await run(cli, ['script', posix(path.resolve(script)), '--empty', '--save-as', posix(file)], {
      env: fontEnv(workspace),
      timeout: 600000,
      signal: o.signal,
      onLine: (line) => {
        if (!line.startsWith('THESIUM_REPORT ') && !line.startsWith('saved ')) {
          lines.push(line);
          o.log?.(`build: ${line}`);
        }
      },
    });
  } catch (error) {
    const message = String(/** @type {Error} */ (error).message).replaceAll(posix(path.resolve(script)), WRAPPER);
    throw new Error(`film/build.jsx failed in EffectCraft:\n${message}`);
  }
  const line = result.stdout.split(/\r?\n/).find((l) => l.startsWith('THESIUM_REPORT '));
  const report = line ? JSON.parse(line.slice('THESIUM_REPORT '.length)) : { comps: [], texts: [], missingFonts: [] };
  report.output = lines.slice(-40);
  const film = report.comps.find((c) => c.name === comp);
  const problems = [];
  if (!film) problems.push(`The script made no composition named "${comp}" (made: ${report.comps.map((c) => c.name).join(', ') || 'none'}). Start with T.film().`);
  else {
    if (film.width !== m.width || film.height !== m.height) problems.push(`"${comp}" is ${film.width}×${film.height}; thesium.json says ${m.width}×${m.height}`);
    if (Math.abs(film.fps - m.fps) > 0.01) problems.push(`"${comp}" runs at ${film.fps} fps; thesium.json says ${m.fps}`);
    if (Math.abs(film.duration - m.duration) > 0.5 / m.fps) problems.push(`"${comp}" lasts ${film.duration} s; thesium.json says ${m.duration}`);
  }
  for (const f of report.missingFonts)
    problems.push(`Font "${f.font}" ${f.style || ''} is not available (layer "${f.layer}" in "${f.comp}") and would silently fall back; run \`thesium fonts\` for the families EffectCraft sees`);
  if (problems.length) throw new Error(`The EffectCraft build is not what thesium.json describes:\n- ${problems.join('\n- ')}`);
  await writeFile(reportFile, JSON.stringify(report, null, 1));
  // Keep only the few most recent builds.
  const builds = (await readdir(dir)).filter((f) => f.endsWith('.ecproj'));
  if (builds.length > 6) {
    const dated = await Promise.all(builds.map(async (f) => ({ f, at: (await stat(path.join(dir, f))).mtimeMs })));
    for (const { f } of dated.sort((a, b) => a.at - b.at).slice(0, builds.length - 6)) {
      await rm(path.join(dir, f), { force: true });
      await rm(path.join(dir, `${f}.json`), { force: true });
    }
  }
  return { file, report, cached: false };
}

/**
 * Effects whose name contains `filter`, with every parameter id, type, default and range.
 * @param {string} [filter]
 */
export async function listEffects(filter = '') {
  const cli = await effectcraftEngine.cli();
  const { stdout } = await run(cli, ['exec', 'effect.list', JSON.stringify(filter ? { filter } : {}), '--empty', '--json'], { timeout: 60000 });
  const data = JSON.parse(stdout);
  return /** @type {Array<{ name: string, category: string, id: string, gpu: boolean, params: any[] }>} */ (Array.isArray(data) ? data : data.effects || []);
}

/** Families and styles EffectCraft can draw for this film. @param {string} workspace */
export async function listFonts(workspace) {
  const cli = await effectcraftEngine.cli();
  const { stdout } = await run(cli, ['exec', 'text.fonts', '{}', '--empty', '--json'], { env: fontEnv(workspace), timeout: 60000 });
  return /** @type {Array<{ family: string, styles: string[], origin: string }>} */ (JSON.parse(stdout).families || []);
}
